function dateSeed(date: string): number {
  const [y, m, d] = date.split("-").map(Number);
  return y * 372 + m * 31 + d;
}

export function getWordForDate(date: string): WordEntry {
  const index = dateSeed(date) % wordBank.length;
  return wordBank[index];
}

const WOTD_SEEN_KEY = "lsrw-wotd-seen";

export function hasSeenWordToday(studentId: string, date: string): boolean {
  try {
    const raw = localStorage.getItem(`${WOTD_SEEN_KEY}-${studentId}-${date}`);
    return raw === "1";
  } catch {
    return false;
  }
}

export function markWordSeen(studentId: string, date: string) {
  try {
    localStorage.setItem(`${WOTD_SEEN_KEY}-${studentId}-${date}`, "1");
  } catch {
    /* ignore */
  }
}

export function formatWordMessage(word: WordEntry, date: string): string {
  return [
    `📚 **Word of the Day** (${date})`,
    ``,
    `**${word.word}** (${word.partOfSpeech})`,
    `🔊 ${word.pronunciation}`,
    ``,
    `**Meaning:** ${word.meaning}`,
    word.hindi ? `**Hindi:** ${word.hindi}` : "",
    ``,
    `**Example:** "${word.example}"`,
  ]
    .filter(Boolean)
    .join("\n");
}
